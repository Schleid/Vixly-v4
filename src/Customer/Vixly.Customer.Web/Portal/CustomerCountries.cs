    // Code and name, sorted by name in the current language.
    public static IReadOnlyList<(string Code, string Name)> Sorted() =>
        Codes.Select(code => (code, Name(code))).OrderBy(item => item.Item2, StringComparer.Create(CultureInfo.CurrentUICulture, true)).ToArray();

    public static string Name(string code)
    {
        try
        {
            RegionInfo region = new(code);
            return region.DisplayName == region.Name ? region.NativeName : region.DisplayName;
        }
        catch (ArgumentException)
        {
            return code;
        }
    }
